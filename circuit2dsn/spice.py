"""Netlist JSON -> SPICE netlist (.cir) and a parts list (BOM, .csv).

SPICE lines follow each part's class: R / C / L / D (anode, cathode when the
orientation model gave pin roles) / Q (C B E) / M (D G S S); anything else
becomes an X subcircuit line with its pins in order. Ground becomes node 0.
Values are the matched text when confident, otherwise a placeholder. This is
a connectivity netlist for checking or simulation setup, not a ready model.
"""

from __future__ import annotations

import csv
import io
import re

from .edif import PREFIX, ascii_text, pin_order

SPICE_LETTER = {"resistor": "R", "potentiometer": "R", "capacitor": "C", "inductor": "L", "diode": "D",
                "led": "D", "bjt": "Q", "mosfet": "M"}
ROLE_ORDER = {"D": ("A", "K"), "Q": ("C", "B", "E"), "M": ("D", "G", "S")}
SKIP = {"ground", "power", "port", "terminal", "no_connect", "wire_hop", "mounting_hole", "net_tie"}


def _node(name: str) -> str:
    n = re.sub(r"[^A-Za-z0-9_+-]", "_", ascii_text(name or "")) or "N"
    return "0" if n.upper() in ("GND", "0", "AGND", "DGND", "COMMON", "VSS") else n


def designators(netlist: dict) -> dict[str, str]:
    """Unique reference designators: matched text when confident and unique, else R_1, Q_2, ..."""
    seen, out, used = {}, {}, set()
    for p in netlist["parts"]:
        d = p.get("designator")
        if d and d[1] >= 0.5:
            seen[ascii_text(d[0]).upper()] = seen.get(ascii_text(d[0]).upper(), 0) + 1
    for p in netlist["parts"]:
        d = p.get("designator")
        t = ascii_text(d[0]) if d and d[1] >= 0.5 else ""
        if t and seen[t.upper()] == 1:
            out[p["id"]] = t
            used.add(t.upper())
    # Names not read from the drawing get a visibly made-up form (R_1, Q_2) so
    # they are never mistaken for, or collide with, the drawing's own labels.
    counters: dict = {}
    for p in netlist["parts"]:
        if p["id"] in out:
            continue
        pre = PREFIX.get(p["cls"], "X")
        counters[pre] = counters.get(pre, 0) + 1
        out[p["id"]] = f"{pre}_{counters[pre]}"
    return out


def to_spice(netlist: dict, title: str = "circuit") -> str:
    names = designators(netlist)
    net_name = {n["id"]: _node(n.get("name") or n["id"]) for n in netlist["nets"]}
    gnd = {n["id"] for n in netlist["nets"] if (n.get("name") or "").upper() == "GND"}
    for nid in gnd:
        net_name[nid] = "0"
    pins_of: dict = {}
    for pid, q in netlist["pins"].items():
        pins_of.setdefault(q["part"], []).append(pid)
    lines = [f"* {title}", "* generated by circuit2dsn from a schematic image: check before simulating", ""]
    for p in netlist["parts"]:
        if p["cls"] in SKIP:
            continue
        pins = sorted(pins_of.get(p["id"], []), key=pin_order)
        if not pins:
            continue
        letter = SPICE_LETTER.get(p["cls"], "X")
        if letter in ROLE_ORDER:          # order pins by role when the orientation model knows them
            roles = {netlist["pins"][q].get("role", [None])[0] if netlist["pins"][q].get("role") else None: q for q in pins}
            want = ROLE_ORDER[letter]
            if all(r in roles for r in want[:len(pins)]):
                pins = [roles[r] for r in want if r in roles]
        nodes = [net_name.get(netlist["pins"][q]["net"], "NC") for q in pins]
        if letter == "M" and len(nodes) == 3:
            nodes.append(nodes[2])        # bulk tied to source
        value = p.get("value")
        val = ascii_text(value[0]) if value and value[1] >= 0.5 else ""
        ref = names[p["id"]]
        name = ref if ref.upper().startswith(letter) else f"{letter}{ref}"
        if letter in "RCL":
            nodes = nodes[:2] + ["NC"] * (2 - len(nodes[:2]))
            lines.append(f"{name} {' '.join(nodes)} {val or '1'}")
        elif letter == "D":
            lines.append(f"{name} {' '.join(nodes[:2])} DMOD")
        elif letter == "Q":
            lines.append(f"{name} {' '.join(nodes[:3])} QMOD")
        elif letter == "M":
            lines.append(f"{name} {' '.join(nodes[:4])} MMOD")
        else:
            lines.append(f"X{ref} {' '.join(nodes)} {re.sub(r'[^A-Za-z0-9_]', '_', p['cls']).upper()}")
    lines += ["", ".end", ""]
    return "\n".join(lines)


def to_bom(netlist: dict) -> str:
    names = designators(netlist)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["designator", "type", "value", "pins", "detection_confidence", "designator_read", "value_read"])
    pins = {}
    for q in netlist["pins"].values():
        pins[q["part"]] = pins.get(q["part"], 0) + 1
    for p in sorted(netlist["parts"], key=lambda p: (p["cls"], names[p["id"]])):
        d, v = p.get("designator"), p.get("value")
        w.writerow([names[p["id"]], p["cls"], (v[0] if v and v[1] >= 0.5 else ""), pins.get(p["id"], 0),
                    f"{p.get('conf', 1.0):.2f}", "yes" if d and d[1] >= 0.5 else "no", "yes" if v and v[1] >= 0.5 else "no"])
    return buf.getvalue()
